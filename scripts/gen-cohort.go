// Command gen-cohort enumerates the MCP registry packages population and
// writes the frozen control-cohort member list for plumbline-cohort-v1.
package main

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/GautamTalksDev/Plumbline/internal/crawler"
)

func main() {
	outPath := "docs/cohort-v1-members.txt"
	mdPath := "docs/COHORT.md"
	if len(os.Args) > 1 {
		outPath = os.Args[1]
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()

	reg := crawler.NewHTTPRegistry(crawler.DefaultRegistryURL, crawler.UserAgent)
	var eligible []string
	var packagesTotal int
	cursor := ""
	for {
		page, next, err := reg.ListServers(ctx, cursor, 100)
		if err != nil {
			fmt.Fprintf(os.Stderr, "registry: %v\n", err)
			os.Exit(1)
		}
		for _, s := range page {
			if !crawler.HasPackages(s) {
				continue
			}
			packagesTotal++
			if !crawler.CohortEligible(s) {
				continue
			}
			eligible = append(eligible, s.Name)
		}
		if next == "" {
			break
		}
		cursor = next
		time.Sleep(100 * time.Millisecond)
	}
	sort.Strings(eligible)

	var members []string
	for _, id := range eligible {
		if crawler.InControlCohort(id) {
			members = append(members, id)
		}
	}

	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil { //nolint:gosec // G301 -- public cohort list parent directory
		fatal(err)
	}
	var b strings.Builder
	b.WriteString("# Frozen control cohort members — plumbline-cohort-v1\n")
	b.WriteString("# Regenerated by: go run ./scripts/gen-cohort.go\n")
	b.WriteString("# Eligibility: packages population ∩ npm/pypi primary ∩ hash cohort\n")
	b.WriteString("# Do not edit mid-study. Departures are recorded, not replaced.\n")
	for _, id := range members {
		b.WriteString(id)
		b.WriteByte('\n')
	}
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil { //nolint:gosec // G306 -- public cohort member list, world-readable by design
		fatal(err)
	}

	md := fmt.Sprintf(`# Control cohort (plumbline-cohort-v1)

This is the scientific control for Plumbline weekly crawls. Cohort members are
spawned **every week** regardless of version change, to catch description-only
drift that a version poll cannot see.

## Definition

A server id is in the cohort iff **all** of:

1. It is in the **packages population** (non-empty `+"`packages[]`"+`).
2. Its primary package registry type is **npm or pypi** (installable).
3. The hash rule holds:

`+"```"+`
uint64(first 8 bytes of SHA-256("plumbline-cohort-v1|" + server_id)) mod 10000 < 500
`+"```"+`

- Cohort version string: `+"`plumbline-cohort-v1`"+`
- Modulus: 10000
- Threshold: 500 (~5%% of the eligible installable packages population)
- Selection depends on **nothing but** the server id and the cohort version
  string — no randomness, timestamps, or local state — once eligibility is met.

## Why npm/pypi only

Tier-2 spawn performs a real install (`+"`npm install --ignore-scripts`"+` /
`+"`pip install --target`"+`) then executes the resolved entrypoint with network
denied. **oci** and **mcpb** packages have no install path in this crawler, so
they cannot be spawned. Including them would force a tier-1 class
(`+"`unpollable`"+`) into the spawn phase. They are therefore excluded from cohort
eligibility at generation time. Remotes-only servers remain out of scope for v1.

## Freeze policy

The member list is frozen for the study. Do not add or remove members
mid-study. Servers that leave the registry are recorded as `+"`departed`"+`,
not replaced. Regenerating after week 1 starts requires a new cohort version.

## Snapshot (generated)

- Packages population size at generation: **%d**
- Installable (npm/pypi) eligible pool: **%d**
- Cohort members: **%d**
- Member list file: [`+"`cohort-v1-members.txt`"+`](cohort-v1-members.txt)

Regenerate (operators only; do not commit a mid-study regen without a new
cohort version):

`+"```"+`bash
go run ./scripts/gen-cohort.go
`+"```"+`

Anyone can recompute membership for an arbitrary id with the definition
above, or by calling `+"`crawler.InControlCohort(id)`"+` ∩
`+"`crawler.CohortEligible(server)`"+` in Go.
`, packagesTotal, len(eligible), len(members))

	if err := os.WriteFile(mdPath, []byte(md), 0o644); err != nil { //nolint:gosec // G306 -- public COHORT.md, world-readable by design
		fatal(err)
	}
	fmt.Printf("packages=%d eligible=%d cohort=%d wrote %s and %s\n", packagesTotal, len(eligible), len(members), outPath, mdPath)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
