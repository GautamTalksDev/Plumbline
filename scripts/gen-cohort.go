// Command gen-cohort enumerates the MCP registry packages population and
// writes the frozen control-cohort member list for plumbline-cohort-v1.
package main

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/GautamTalksDev/Plumbline/internal/crawler"
)

func main() {
	outPath := "docs/cohort-v1-members.txt"
	mdPath := "docs/COHORT.md"
	if len(os.Args) > 1 {
		outPath = os.Args[1]
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()

	reg := crawler.NewHTTPRegistry(crawler.DefaultRegistryURL, crawler.UserAgent)
	var packages []string
	cursor := ""
	for {
		page, next, err := reg.ListServers(ctx, cursor, 100)
		if err != nil {
			fmt.Fprintf(os.Stderr, "registry: %v\n", err)
			os.Exit(1)
		}
		for _, s := range page {
			if crawler.HasPackages(s) {
				packages = append(packages, s.Name)
			}
		}
		if next == "" {
			break
		}
		cursor = next
		time.Sleep(100 * time.Millisecond)
	}
	sort.Strings(packages)

	var members []string
	for _, id := range packages {
		if crawler.InControlCohort(id) {
			members = append(members, id)
		}
	}

	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fatal(err)
	}
	var b strings.Builder
	b.WriteString("# Frozen control cohort members — plumbline-cohort-v1\n")
	b.WriteString("# Regenerated by: go run ./scripts/gen-cohort.go\n")
	b.WriteString("# Do not edit mid-study. Departures are recorded, not replaced.\n")
	for _, id := range members {
		b.WriteString(id)
		b.WriteByte('\n')
	}
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}

	md := fmt.Sprintf(`# Control cohort (plumbline-cohort-v1)

This is the scientific control for Plumbline weekly crawls. Cohort members are
spawned **every week** regardless of version change, to catch description-only
drift that a version poll cannot see.

## Definition

A server id is in the cohort iff:

`+"```"+`
uint64(first 8 bytes of SHA-256("plumbline-cohort-v1|" + server_id)) mod 10000 < 500
`+"```"+`

- Cohort version string: `+"`plumbline-cohort-v1`"+`
- Modulus: 10000
- Threshold: 500 (~5%% of the packages population)
- Selection depends on **nothing but** the server id and the cohort version
  string — no randomness, timestamps, or local state.

## Scope

The cohort is drawn from the **packages population** only (servers with
non-empty `+"`packages[]`"+`). Remotes-only servers are out of scope for v1.

## Freeze policy

The member list is frozen for the study. Do not add or remove members
mid-study. Servers that leave the registry are recorded as `+"`departed`"+`,
not replaced.

## Snapshot (generated)

- Packages population size at generation: **%d**
- Cohort members: **%d**
- Member list file: [`+"`cohort-v1-members.txt`"+`](cohort-v1-members.txt)

Regenerate (operators only; do not commit a mid-study regen without a new
cohort version):

`+"```"+`bash
go run ./scripts/gen-cohort.go
`+"```"+`

Anyone can recompute membership for an arbitrary id with the definition
above, or by calling `+"`crawler.InControlCohort(id)`"+` in Go.
`, len(packages), len(members))

	if err := os.WriteFile(mdPath, []byte(md), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("packages=%d cohort=%d wrote %s and %s\n", len(packages), len(members), outPath, mdPath)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
